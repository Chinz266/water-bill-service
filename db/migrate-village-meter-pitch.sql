-- =====================================================================
-- เพิ่ม "ระยะเดินเฉลี่ยต่อ 1 มิเตอร์" ให้ข้อมูลหมู่บ้าน
--
-- ═══ ปัญหาที่แก้ ═══
--
-- ScanBatchService เคยใช้ค่าคงที่ GPS_FAR_M = 150 ม. เป็นระยะ "ไกลจนน่าสงสัย"
-- ทั้งระบบ ซึ่งเหมาะกับหมู่บ้านชนบทที่มิเตอร์ห่างกัน 15 ม. เท่านั้น
--
-- พอเอาไปใช้กับชุมชนกึ่งเมือง/ทาวน์โฮมที่มิเตอร์ห่างกัน 4-8 ม. รัศมี 150 ม.
-- จะครอบบ้านราว 100 หลัง = 2 ใน 3 ของหมู่บ้านขนาดปกติ (100-200 หลังคาเรือน)
-- กลายเป็นด่านที่แทบไม่ตัดอะไรทิ้ง แต่ยังคิดค่าใช้จ่ายในการคำนวณเท่าเดิม
--
-- ═══ ทำไมเก็บ "ระยะเดิน" ไม่ใช่ "ระยะห่างระหว่างบ้าน" ═══
--
-- ระยะห่างระหว่างตัวบ้านวัดเป็นเส้นตรง แต่คนจดมิเตอร์เดินเลาะรั้วและสลับ
-- ข้ามฝั่งถนน ระยะที่เดินจริงต่อมิเตอร์หนึ่งตัวจึงมากกว่าเสมอ — ค่านี้คือสิ่งที่
-- เอาไปคูณเพื่อหารัศมีได้ตรงกว่า (ชนบท 10-15 ม. / ทาวน์โฮม 4-8 ม.)
--
-- NULL = ยังไม่ได้กรอก ระบบจะใช้ค่ากลาง 15 ม. (พฤติกรรมเดิมทุกประการ)
-- จึงปลอดภัยที่จะรัน migration นี้โดยไม่ต้องไปกรอกค่าให้ครบก่อน
--
-- รันคำสั่งนี้ครั้งเดียว:
--   npm run migrate -- db/migrate-village-meter-pitch.sql
-- =====================================================================

-- ฐานข้อมูลมาจาก DB_DATABASE ใน .env (ตัวรันเลือกให้ตอนต่อ) — ไฟล์นี้จึงไม่ USE เอง
-- รันด้วยมือใน phpMyAdmin/CLI ต้องเลือกฐานข้อมูลก่อน

SET NAMES utf8mb4;

ALTER TABLE `villages`
  ADD COLUMN `meter_pitch_m` smallint unsigned DEFAULT NULL
    COMMENT 'ระยะเดินเฉลี่ยต่อ 1 มิเตอร์ เป็นเมตร (NULL = ใช้ค่ากลาง 15)'
    AFTER `billing_month`;

-- ไล่ดูว่าหมู่บ้านไหนยังไม่ได้กรอก — ปล่อยไว้ก็ได้ ระบบใช้ค่ากลางแทน
-- แต่หมู่บ้านที่เป็นทาวน์โฮม/ชุมชนแออัดควรไปกรอกที่หน้าตั้งค่าหมู่บ้าน
-- ไม่งั้นด่าน GPS จะหลวมเกินจริงสำหรับหมู่บ้านนั้น
SELECT `id`, `village_name`, `village_no`, `meter_pitch_m`
FROM `villages`
ORDER BY `id`;
