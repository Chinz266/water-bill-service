-- ที่มา: หน้าสแกนเดิมยิงสองรอบ (สร้าง meter_reading → สร้างบิล)
--        ถ้ารอบสองโดนปฏิเสธ (บิลซ้ำเดือน / หน่วยน้ำผิดปกติ) แถวที่จดไปแล้วค้างอยู่
--        แก้ที่ต้นเหตุแล้วด้วย POST /bills/scan ที่เขียนทั้งคู่ในทรานแซกชันเดียว
--
-- ⚠️ ห้ามลบ "การจดครั้งแรกสุดของแต่ละบ้าน" เพราะนั่นคือเลขมิเตอร์ ณ วันลงทะเบียน
--    ซึ่ง getPreviousUnit() ใช้เป็นเลขตั้งต้นของบิลใบแรก ลบทิ้งแล้วบ้านนั้นจะโดน
--    คิดค่าน้ำย้อนหลังตั้งแต่ 0
--
-- วิธีใช้: ดูผลจากขั้นที่ 1 ก่อนว่าตรงกับที่ตั้งใจไหม แล้วค่อยรันขั้นที่ 2
