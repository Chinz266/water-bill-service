-- ⚠️ ไฟล์นี้รันด้วยมือ (ไม่ผ่าน npm run migrate) — เลือกฐานข้อมูลให้ถูกก่อนรัน
--    ชื่อฐานข้อมูลจริงอยู่ที่ DB_DATABASE ใน .env ที่เดียว
SET NAMES utf8mb4;

-- ---------------------------------------------------------------------
-- ขั้นที่ 1: ดูก่อนว่าจะลบแถวไหนบ้าง (ยังไม่ลบอะไร)
-- ---------------------------------------------------------------------
SELECT
  r.id,
  r.members_id1 AS member,
  r.meter_unit,
  r.reading_date
FROM meter_readings r
LEFT JOIN bills b ON b.meter_readings_id = r.id
WHERE b.id IS NULL
  -- เก็บแถวเก่าสุดของแต่ละบ้านไว้ = เลขตอนลงทะเบียน
  AND r.id <> (
    SELECT MIN(r2.id) FROM (SELECT * FROM meter_readings) r2
    WHERE r2.members_id1 = r.members_id1
  )
ORDER BY r.members_id1, r.id;

