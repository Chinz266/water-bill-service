-- =====================================================================
-- ขยาย members.longitude จาก decimal(10,8) เป็น decimal(11,8)
--
-- ปัญหา: decimal(10,8) = 10 หลักรวม, 8 หลักหลังจุด → เหลือหน้าจุดแค่ 2 หลัก
--        ค่าสูงสุดที่เก็บได้คือ 99.99999999
--        แต่ลองจิจูดของประเทศไทยอยู่ที่ 97.3 – 105.6 ซึ่งเป็นเลข 3 หลัก
--        ทุกจังหวัดตั้งแต่ลองจิจูด 100 ขึ้นไป (กรุงเทพ 100.5, โคราช 102.1,
--        อุบล 104.9) จึงบันทึกไม่ได้เลย
--
-- อาการที่เจอ: - MySQL strict mode  → ERROR 1264 Out of range value
--              - MySQL ไม่ strict   → ค่าถูกตัดเหลือ 99.99999999 เงียบ ๆ
--                                      (พิกัดเพี้ยนไปหลายร้อยกิโลเมตร)
--
-- latitude ไม่ต้องแก้ — ไทยอยู่ที่ 5.6 – 20.5 เป็นเลข 2 หลัก decimal(10,8) พอดี
--
-- รันคำสั่งนี้ครั้งเดียว:
--   npm run migrate -- db/migrate-longitude-precision.sql
-- =====================================================================

-- ฐานข้อมูลมาจาก DB_DATABASE ใน .env (ตัวรันเลือกให้ตอนต่อ) — ไฟล์นี้จึงไม่ USE เอง
-- รันด้วยมือใน phpMyAdmin/CLI ต้องเลือกฐานข้อมูลก่อน

ALTER TABLE `members`
  MODIFY COLUMN `longitude` decimal(11,8) DEFAULT NULL
  COMMENT 'พิกัดลองจิจูด (ต้องเป็น 11,8 ลองจิจูดไทย 97-106 มี 3 หลักหน้าจุด)';

-- ⚠️ แถวที่บันทึกไปแล้วก่อนแก้ schema กู้คืนไม่ได้ — ค่าที่ถูกตัดไปเหลือ
--    99.99999999 ไม่มีข้อมูลเดิมหลงเหลือให้ย้อนกลับ ต้องกรอกพิกัดใหม่
--    คิวรีนี้ไล่ดูว่ามีบ้านไหนโดนบ้าง (ค่าที่ชิดเพดานเป๊ะ = โดนตัดแน่นอน)
SELECT `id`, `house_no`, `latitude`, `longitude`
FROM `members`
WHERE `longitude` >= 99.9
ORDER BY `id`;
