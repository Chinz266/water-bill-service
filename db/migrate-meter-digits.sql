-- =====================================================================
-- เก็บ "จำนวนหลักบนหน้าปัด" ที่ YOLO ตรวจเจอ ในทุกครั้งที่จดด้วย OCR
--
-- ทำไมต้องเก็บ:
--
--   มิเตอร์รุ่นเดียวกันมีจำนวนหลักคงที่ตลอดอายุการใช้งาน บ้านที่หน้าปัด 5 หลัก
--   จะเป็น 5 หลักทุกเดือน ไม่มีวันเปลี่ยน (จนกว่าจะเปลี่ยนมิเตอร์ตัวใหม่)
--
--   ความผิดพลาดของ OCR ที่อันตรายที่สุดคือ "หลักหาย" กับ "หลักเกิน" เพราะยอดเงิน
--   คลาดไป 10 เท่าขึ้นไปในครั้งเดียว ขณะที่ด่านที่มีอยู่จับได้ไม่ครบ:
--     - หลักหาย (1250 → 250)  จับได้บังเอิญ เพราะน้อยกว่าเลขเดือนก่อน
--     - หลักเกิน (125 → 1250) จับได้เฉพาะบ้านที่มีประวัติ ส่วนบ้านใหม่เพดานอยู่ที่
--       1000 หน่วยซึ่งหลวมมาก — เลขที่เกินมาหนึ่งหลักลอดไปได้สบาย
--
--   พอเก็บจำนวนหลักไว้ การเทียบกับครั้งก่อนของบ้านเดียวกันจะจับได้ทั้งสองแบบ
--   ด้วยการเทียบเลขจำนวนเต็มตัวเดียว ไม่ต้องพึ่งประวัติการใช้น้ำเลย
--
-- ค่านี้คือ "จำนวนกล่องตัวเลขที่โมเดลตรวจเจอในกรอบ border_water_meter_number"
-- ไม่ใช่จำนวนหลักของตัวเลขหลังแปลงเป็น int — เลข 00025 นับเป็น 5 ไม่ใช่ 2
-- เพราะเลขศูนย์นำหน้าคือหลักที่มีอยู่จริงบนหน้าปัด
--
-- NULL = การจดครั้งนั้นไม่ได้มาจาก OCR (พนักงานกรอกมือ) ซึ่งเป็นเรื่องปกติ
-- จึงต้องข้ามแถวที่เป็น NULL ตอนหาค่าอ้างอิง ไม่ใช่ถือว่าเป็น 0
--
-- รันคำสั่งนี้ครั้งเดียว:
--   npm run migrate -- db/migrate-meter-digits.sql
-- =====================================================================

USE `water-bill-db`;

SET NAMES utf8mb4;

ALTER TABLE `meter_readings`
  ADD COLUMN `meter_digits` tinyint(4) DEFAULT NULL
    COMMENT 'จำนวนหลักบนหน้าปัดที่ OCR ตรวจเจอ (NULL = กรอกมือ ไม่ได้ผ่าน OCR)'
    AFTER `captured_at`;

-- ตรวจว่าบ้านไหนมีจำนวนหลักไม่คงที่ ซึ่งแปลว่ามีการจดที่ OCR อ่านผิดปนอยู่
-- (หรือเปลี่ยนมิเตอร์ไปแล้วจริง ๆ ซึ่งต้องไล่ดูวันที่ประกอบ)
SELECT
  `members_id1`                  AS members_id,
  COUNT(DISTINCT `meter_digits`) AS distinct_digit_counts,
  GROUP_CONCAT(DISTINCT `meter_digits` ORDER BY `meter_digits`) AS digit_counts_seen
FROM `meter_readings`
WHERE `meter_digits` IS NOT NULL
GROUP BY `members_id1`
HAVING distinct_digit_counts > 1
ORDER BY `members_id1`;
