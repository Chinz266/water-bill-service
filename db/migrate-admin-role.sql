-- =====================================================================
-- แยกผู้ดูแลออกเป็น "เจ้าของระบบ" กับ "คนเดินจด"
--
-- ก่อน migration นี้ทุกบัญชีที่ role='admin' มีสิทธิ์เท่ากันหมด ใครก็แก้เลข
-- มิเตอร์ของบิลเดือนไหนก็ได้ — ซึ่งเป็นช่องที่แก้ยอดเงินย้อนหลังได้เงียบ ๆ
--
-- ⚠️ ชื่อคอลัมน์เป็น `admin_role` ไม่ใช่ `role` เพราะ `role` ถูกใช้ไปแล้วสำหรับ
--    แยก 'admin' (ผู้ดูแล) ออกจาก 'member' (ลูกบ้านที่ล็อกอินดูบิลตัวเอง)
--    สองค่านี้ตอบคนละคำถาม: role = "เข้าหน้าไหนได้" / admin_role = "แก้ของเก่าได้แค่ไหน"
--
-- รันคำสั่งนี้ครั้งเดียว:
--   npm run migrate -- db/migrate-admin-role.sql
-- =====================================================================

USE `water-bill-db`;

SET NAMES utf8mb4;

-- ─────────────────────────────────────────────────────────────────────
-- 1) คอลัมน์ใหม่ — ค่าเริ่มต้นเป็น 'staff'
--
-- บัญชีที่เปิดใหม่หลังจากนี้ (รวมทั้งที่สมัครเองผ่าน POST /auth/register ซึ่งเป็น
-- endpoint สาธารณะ) ต้องได้สิทธิ์ต่ำสุดเสมอ ไม่ใช่ได้สิทธิ์แก้บิลย้อนหลังมาฟรี ๆ
-- การเลื่อนเป็น 'owner' ต้องเป็นการตัดสินใจของคน ไม่ใช่ผลข้างเคียงของการสมัคร
-- ─────────────────────────────────────────────────────────────────────
ALTER TABLE `admin`
  ADD COLUMN `admin_role` enum('owner','staff') NOT NULL DEFAULT 'staff'
    COMMENT 'สิทธิ์ของผู้ดูแล: owner แก้บิลเก่าได้ตลอด / staff แก้ได้เฉพาะที่จดวันนี้หรือยังรอชำระ'
    AFTER `role`;

-- ─────────────────────────────────────────────────────────────────────
-- 2) บัญชีผู้ดูแลที่มีอยู่แล้ว → 'owner'
--
-- ตั้งใจ **ไม่เปลี่ยนพฤติกรรมของระบบที่ใช้งานอยู่** ด้วย migration นี้ —
-- ทุกคนที่เคยแก้ได้ก็ยังแก้ได้เหมือนเดิม ไม่มีใครถูกตัดสิทธิ์กลางคันโดยไม่รู้ตัว
--
-- ⚠️ หลังรันเสร็จให้ไล่ลดสิทธิ์คนที่ควรเป็น staff ด้วยมือ (ตัวอย่างข้างล่าง)
--    ถ้าปล่อยไว้ทั้งหมดเป็น owner ด่านนี้จะไม่ได้กันอะไรเลย
--
--   UPDATE `admin` SET `admin_role` = 'staff' WHERE `email` = 'คนที่เดินจด@example.com';
-- ─────────────────────────────────────────────────────────────────────
UPDATE `admin` SET `admin_role` = 'owner' WHERE `role` = 'admin';

-- ตรวจผลลัพธ์ — ควรเห็น owner เท่ากับจำนวนผู้ดูแลเดิมที่มีอยู่
SELECT `role`, `admin_role`, COUNT(*) AS `accounts`
FROM `admin`
GROUP BY `role`, `admin_role`;
