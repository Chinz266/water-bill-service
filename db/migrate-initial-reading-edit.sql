-- =====================================================================
-- แก้เลขมิเตอร์ตั้งต้นของบ้านที่ลงทะเบียนไปแล้ว (POST /member/initial-reading)
--
-- ═══ ปัญหาที่แก้ ═══
--
-- เลขตั้งต้นถูกกรอกครั้งเดียวตอนลงทะเบียน แล้วแก้ไม่ได้อีกเลย พิมพ์ผิดหลักเดียว
-- (เช่น 1250 เป็น 12500) ทุกบิลของบ้านหลังนั้นจะผิดตามไปตลอด เพราะหน่วยน้ำคิดจาก
-- ผลต่างของเลขครั้งนี้กับครั้งก่อน — ทางแก้เดิมคือลบบ้านทิ้งแล้วลงทะเบียนใหม่
-- ซึ่งพาบิลกับประวัติการจดหายไปด้วยทั้งหมด
--
-- ═══ ทำไมต้องแก้ตารางนี้ ═══
--
-- meter_reading_logs เก็บร่องรอยการแก้เลขมิเตอร์ไว้แล้ว แต่ออกแบบมาสำหรับการแก้
-- "บิลที่ออกไปแล้ว" bills_id จึงเป็น NOT NULL
-- การจดครั้งแรกไม่มีบิล — มันคือเส้นเริ่มต้นที่บิลใบแรกเอาไปลบ ไม่ใช่บิลเอง
-- ถ้าไม่ยอมให้ bills_id เป็น NULL การแก้เลขตั้งต้นจะเขียน log ไม่ได้เลย
-- แล้วการแก้ที่กระทบทุกบิลของบ้านหลังนั้นจะกลายเป็นการแก้ที่ไม่มีร่องรอย
-- ซึ่งแย่กว่าการแก้บิลใบเดียวที่ระบบยังบันทึกไว้อย่างดี
--
-- ═══ อ่าน log ยังไงหลังจากนี้ ═══
--
--   bills_id IS NOT NULL  = แก้เลขของบิลที่ออกไปแล้ว (ของเดิม)
--   bills_id IS NULL      = แก้เลขตั้งต้นตอนลงทะเบียน
--                           คอลัมน์ usage_unit / total_amount ของแถวนั้นเป็น 0 ทั้งคู่
--                           เพราะการจดครั้งแรกไม่มีหน่วยน้ำและไม่มียอดเงิน
--                           **ห้ามอ่านเลข 0 พวกนั้นว่าเป็นยอดจริง** ให้ดูที่ bills_id ก่อนเสมอ
--
-- รันคำสั่งนี้ครั้งเดียว:
--   npm run migrate -- db/migrate-initial-reading-edit.sql
-- =====================================================================

USE `water-bill-db`;

SET NAMES utf8mb4;

ALTER TABLE `meter_reading_logs`
  MODIFY COLUMN `bills_id` int DEFAULT NULL
    COMMENT 'บิลที่ถูกแก้ (NULL = แก้เลขตั้งต้นตอนลงทะเบียน ซึ่งยังไม่มีบิล)';

-- ไล่ดูว่ามีการแก้เลขตั้งต้นไปแล้วกี่ครั้ง ของบ้านไหนบ้าง
SELECT
  `members_id`,
  COUNT(*) AS `initial_edits`,
  MAX(`create_date`) AS `last_edit`
FROM `meter_reading_logs`
WHERE `bills_id` IS NULL
GROUP BY `members_id`
ORDER BY `last_edit` DESC;
