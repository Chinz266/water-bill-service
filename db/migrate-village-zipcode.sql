-- =====================================================================
-- เพิ่ม "รหัสไปรษณีย์" ให้ข้อมูลหมู่บ้าน
--
-- ทำไมเก็บที่ villages ทั้งที่ subdistricts.zip_code มีอยู่แล้ว:
--
--   ตาราง subdistricts เป็นข้อมูลอ้างอิงชุดใหญ่ที่ import เข้ามา ใช้ร่วมกัน
--   ทั้งระบบและควรอ่านอย่างเดียว — ถ้าให้หน้าตั้งค่าแก้ตรงนั้น หมู่บ้านหนึ่ง
--   แก้แล้วจะไปโดนทุกที่ที่อ้างตำบลเดียวกัน
--
--   และรหัสของตำบลก็ไม่ได้ตรงเสมอ: มี 16 ตำบลในตารางที่ค่าเป็น NULL
--   ส่วนตำบลใหญ่บางแห่งแบ่งเขตไปรษณีย์เป็นสองรหัสแต่ตารางเก็บได้ค่าเดียว
--   เจ้าหน้าที่จึงต้องพิมพ์ทับเองได้ที่ระดับหมู่บ้าน
--
-- เก็บเป็น varchar ไม่ใช่ int เพราะเป็น "รหัส" ไม่ใช่จำนวน ไม่มีการบวกลบ
-- และไม่ต้องกลัวศูนย์นำหน้าหายตอนแสดงผล — เหมือน phone ในตารางเดียวกัน
--
-- NULL = ยังไม่ได้กรอก ไม่ได้แปลว่าหมู่บ้านนั้นไม่มีรหัส
--
-- รันคำสั่งนี้ครั้งเดียว:
--   npm run migrate -- db/migrate-village-zipcode.sql
-- =====================================================================

-- ฐานข้อมูลมาจาก DB_DATABASE ใน .env (ตัวรันเลือกให้ตอนต่อ) — ไฟล์นี้จึงไม่ USE เอง
-- รันด้วยมือใน phpMyAdmin/CLI ต้องเลือกฐานข้อมูลก่อน

SET NAMES utf8mb4;

ALTER TABLE `villages`
  ADD COLUMN `zip_code` varchar(5) DEFAULT NULL
    COMMENT 'รหัสไปรษณีย์ของหมู่บ้าน (NULL = ยังไม่ได้กรอก)'
    AFTER `subdistricts_id`;

-- ตั้งค่าเริ่มต้นจากรหัสของตำบลที่เลือกไว้ เพื่อไม่ต้องเปิดหน้าตั้งค่าไปพิมพ์ใหม่
-- คอลัมน์เพิ่งถูกสร้าง ทุกแถวยังเป็น NULL อยู่ จึงไม่มีค่าที่กรอกไว้ให้ทับ
-- (หมู่บ้านที่ตำบลไม่มีรหัสในตารางอ้างอิงจะถูกข้าม ปล่อยเป็น NULL ให้กรอกเอง)
UPDATE `villages` v
  JOIN `subdistricts` s ON s.`id` = v.`subdistricts_id`
  SET v.`zip_code` = s.`zip_code`
WHERE s.`zip_code` IS NOT NULL;

-- ไล่ดูว่าหมู่บ้านไหนยังไม่มีรหัส ต้องไปกรอกเองที่หน้าตั้งค่าหมู่บ้าน
SELECT `id`, `village_name`, `village_no`, `subdistricts_id`, `zip_code`
FROM `villages`
ORDER BY `id`;
