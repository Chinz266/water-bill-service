-- คิว "รอการตรวจสอบ" — รูปที่รู้แล้วว่าบ้านไหน แต่ด่านตีกลับ
--
-- ═══ ปัญหาที่แก้ ═══
--
-- ด่านหลังบ้าน (หน่วยพุ่ง / เลขต่ำกว่าเดือนก่อน / จดสลับตัวในกลุ่มมิเตอร์ที่ติดกัน)
-- ตีกลับด้วย 409 แล้วให้คนหน้างานเลือกเองว่าจะกดยืนยันข้ามหรือไม่ — แต่คนที่ยืนกลางแดด
-- กับมิเตอร์อีก 40 ตัวที่ยังไม่ได้จด ไม่ใช่คนที่ควรตัดสินว่ายอดผิดปกตินี้ถูกหรือผิด
-- เมื่อทางเลือกมีแค่ "กดผ่าน" กับ "ทิ้งงานไว้" คนจะกดผ่าน แล้วด่านทั้งหมดกลายเป็นพิธีกรรม
--
-- ทางแก้คือเพิ่มทางเลือกที่สาม: ฝากไว้ในคิวให้คนที่มีเวลาเปิดรูปเทียบเป็นคนอนุมัติ
--
-- ═══ ทำไมใช้ตาราง unassigned_readings เดิม ไม่สร้างตารางใหม่ ═══
--
-- ตารางนั้นคือ "รูปที่ยังออกบิลไม่ได้ รอคนตัดสิน" อยู่แล้ว ทั้ง flow อนุมัติ (assign)
-- ตีทิ้ง (discard) การเก็บรูป และหน้าจอของ Admin ใช้ซ้ำได้ทั้งหมด
-- ต่างกันแค่ "รู้บ้านแล้วหรือยัง" ซึ่งเป็นข้อมูลหนึ่งคอลัมน์ ไม่ใช่ชนิดของงานคนละอย่าง
-- แยกตารางจะได้คิวสองอันที่ Admin ต้องไล่ดูสองที่ โดยที่ปุ่มบนหน้าจอทำงานเหมือนกันเป๊ะ
--
-- ═══ ความหมายของสามคอลัมน์ ═══
--
--   members_id      บ้านที่คนหน้างานเลือกไว้แล้ว (NULL = รูปกำพร้าแท้ ๆ ยังไม่รู้ว่าของใคร)
--                   เป็นแค่ "ข้อเสนอ" คนตรวจเปลี่ยนบ้านตอนกดจับคู่ได้เสมอ — เพราะเหตุผลหนึ่ง
--                   ที่รูปมาอยู่ตรงนี้คือ "อาจจดสลับบ้าน" ซึ่งแปลว่าบ้านที่เลือกไว้อาจผิด
--
--   blocked_code    รหัสด่านที่ตีกลับ (HIGH_USAGE, METER_ROLLBACK, CLUSTER_SEQUENCE_MISMATCH …)
--                   เก็บรหัสไม่ใช่แค่ข้อความ เพราะหน้าตรวจต้องรู้ว่าจะขึ้นช่องยืนยันตัวไหนให้กด
--                   ถ้าดูจากข้อความ หน้าจอจะพังทันทีที่มีใครไปแก้คำในข้อความนั้น
--
--   blocked_reason  ข้อความที่ด่านตอบกลับไปตอนนั้น — ให้คนตรวจเห็นสิ่งเดียวกับที่คนหน้างานเห็น
--
-- ⚠️ ไม่ผูก FOREIGN KEY กับ members ตั้งใจ — แถวในคิวเป็นแค่ข้อเสนอที่ยังไม่มีผลต่อยอดเงิน
--    และต้องอ่านย้อนหลังได้แม้บ้านหลังนั้นจะถูกลบไปแล้ว (ตัวที่มี FK จริงคือ meter_readings
--    ซึ่งเกิดตอนอนุมัติผ่าน POST /bills/scan) ความมีอยู่จริงของบ้านตรวจที่ชั้น service แทน
--
-- รันคำสั่งนี้ครั้งเดียว:
--   npm run migrate -- db/migrate-review-queue.sql
-- =====================================================================

USE `water-bill-db`;

SET NAMES utf8mb4;

ALTER TABLE `unassigned_readings`
  ADD COLUMN `members_id` int DEFAULT NULL
    COMMENT 'บ้านที่คนหน้างานเลือกไว้ (NULL = ยังไม่รู้ว่าของบ้านไหน)'
    AFTER `villages_id`,
  ADD COLUMN `blocked_code` varchar(45) DEFAULT NULL
    COMMENT 'รหัสด่านที่ตีกลับ เช่น HIGH_USAGE — หน้าตรวจใช้เลือกช่องยืนยันที่ต้องกด'
    AFTER `members_id`,
  ADD COLUMN `blocked_reason` varchar(500) DEFAULT NULL
    COMMENT 'ข้อความที่ด่านตอบกลับตอนนั้น'
    AFTER `blocked_code`;

-- ไล่ดูว่าบ้านหลังไหนมีของค้างรอตรวจอยู่ (หน้าบ้านหลังเดียวกันซ้ำ ๆ = สัญญาณว่ามิเตอร์มีปัญหาจริง)
ALTER TABLE `unassigned_readings`
  ADD KEY `idx_unassigned_member` (`members_id`);

-- ของที่ค้างอยู่ตอนนี้ แยกตามเหตุผลที่ถูกตีกลับ
SELECT
  COALESCE(`blocked_code`, '(ไม่รู้ว่าบ้านไหน)') AS `reason`,
  COUNT(*) AS `pending`,
  MIN(`create_date`) AS `oldest`
FROM `unassigned_readings`
WHERE `status` = 'Pending'
GROUP BY `reason`
ORDER BY `pending` DESC;
